/**
 * SVG 아이콘 HTML 생성
 * @param {string} name - 아이콘 이름 (ICONS 객체의 key)
 * @param {string} [className=''] - 추가 CSS 클래스
 * @returns {string} SVG HTML 문자열
 *
 * @example
 * icon('search')                    // 기본
 * icon('search', 'icon-lg')         // 큰 아이콘
 * icon('search', 'icon-sm icon-muted') // 작고 흐린 아이콘
 * icon('settings', 'icon-primary')  // 프라이머리 색상
 */
function icon(name, className = '') {
  const path = ICONS[name];

  if (!path) {
    console.warn(`[icon] "${name}" 아이콘을 찾을 수 없습니다.`);
    return '';
  }

  const classes = ['icon', className].filter(Boolean).join(' ');

  return `<svg class="${classes}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

/**
 * 아이콘 존재 여부 확인
 * @param {string} name - 아이콘 이름
 * @returns {boolean}
 */
function hasIcon(name) {
  return name in ICONS;
}

/**
 * 모든 아이콘 이름 반환
 * @returns {string[]}
 */
function getIconNames() {
  return Object.keys(ICONS);
}

